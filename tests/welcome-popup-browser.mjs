import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createService } from '../server/app.mjs';
import { hashPassword } from '../server/security.mjs';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || path.resolve(os.homedir(), '.claude/skills/gstack/node_modules/playwright/index.mjs')));
const directory = await mkdtemp(path.join(os.tmpdir(), 'ego-popup-browser-'));
const base = 'http://127.0.0.1:4396', service = createService({ directory, origin: base });
const output = path.resolve('.artifacts/welcome-popup-browser'); await mkdir(output, { recursive: true });
await new Promise(resolve => service.server.listen(4396, '127.0.0.1', resolve));
const password = 'Popup-browser-QA-only-2026!', at = service.store.now();
service.store.run('INSERT INTO users(id,email,password,name,role,createdAt,updatedAt) VALUES(?,?,?,?,?,?,?)', 'popup-admin', 'popup-admin@example.test', await hashPassword(password), '관리자', 'admin', at, at);
const browser = await chromium.launch({ headless: true });
const adminContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const memberContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
const admin = await adminContext.newPage(), member = await memberContext.newPage();
const errors = []; for (const page of [admin, member]) page.on('pageerror', error => errors.push(error.message));
try {
  const adminLogin = await adminContext.request.post(base + '/api/auth/login', { headers: { Origin: base }, data: { email: 'popup-admin@example.test', password } }); assert.equal(adminLogin.status(), 200);
  await admin.goto(base + '/admin/#settings');
  const form = admin.locator('.admin-welcome-popup form'); await form.waitFor();
  await form.locator('[name=title]').fill('<img src=x onerror=alert(1)>');
  await form.locator('[data-popup-preview]').click();
  await admin.locator('.ego-welcome-dialog[open]').waitFor();
  assert.equal(await admin.locator('.ego-welcome-dialog h2').textContent(), '<img src=x onerror=alert(1)>');
  assert.equal(await admin.locator('.ego-welcome-dialog h2 img').count(), 0, 'preview renders title as plain text');
  await admin.locator('.ego-welcome-close').click();
  await form.locator('[name=title]').fill('첫 촬영을 준비해볼까요?');
  await form.locator('[name=body]').fill('촬영 전에 구도와 주의사항을 확인해보세요.\n내 시점으로 일상의 활동을 기록해요.');
  await form.locator('[type=submit]').click();
  await form.getByText(/팝업을 저장했습니다/).waitFor();
  await form.locator('[data-popup-preview]').click();
  await admin.locator('.ego-welcome-dialog').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)));
  await admin.screenshot({ path: path.join(output, 'admin-preview.png'), fullPage: true });
  await admin.locator('.ego-welcome-close').click();
  const registration = await memberContext.request.post(base + '/api/auth/register', { headers: { Origin: base }, data: { email: 'popup-member@example.test', password, name: '참여자', adult: true, terms: true, privacy: true } }); assert.equal(registration.status(), 201);
  await member.goto(base + '/app/#home');
  await member.locator('.ego-welcome-dialog[open]').waitFor({ timeout: 15000 });
  await member.evaluate(() => document.fonts.ready);
  await member.locator('.ego-welcome-dialog').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)));
  assert.equal(await member.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const popupBox = await member.locator('.ego-welcome-dialog').boundingBox(); assert.ok(popupBox.x >= 0 && popupBox.x + popupBox.width <= 390);
  await member.screenshot({ path: path.join(output, 'member-popup-390.png'), fullPage: false });
  await member.locator('.ego-welcome-primary').click();
  await member.waitForURL('**/#education');
  await member.reload(); await member.waitForLoadState('networkidle');
  assert.equal(await member.locator('.ego-welcome-dialog[open]').count(), 0, 'once receipt persists across browser reload');
  // A new version is eligible again; logout closes a visible private popup.
  await form.locator('[name=title]').fill('새로운 촬영 안내'); await form.locator('[type=submit]').click(); await form.getByText(/팝업을 저장했습니다/).waitFor();
  await member.goto(base + '/app/#home'); await member.reload(); await member.locator('.ego-welcome-dialog[open]').waitFor();
  await member.evaluate(async () => { const online = await import('/studio/online-api.js'); await online.api('/auth/logout', { method: 'POST' }); await online.refreshSession(); });
  await member.locator('.ego-welcome-dialog').waitFor({ state: 'detached' });
  assert.deepEqual(errors, []);
  console.log('Welcome popup browser passed: administrator edit/preview/save, text safety, authenticated 390px dialog, CTA navigation, once after reload, account logout closure.');
} catch (error) {
  await member.screenshot({ path: path.join(output, 'failure-member.png') }).catch(() => {});
  await admin.screenshot({ path: path.join(output, 'failure-admin.png') }).catch(() => {});
  throw error;
} finally { await browser.close(); await service.close(); await rm(directory, { recursive: true, force: true }); }
