  const textBindings = [...document.querySelectorAll('[data-i18n-text]')].flatMap(element => {
    const nodes = [...element.childNodes].filter(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim());
    return JSON.parse(element.dataset.i18nText).map((key, index) => ({node: nodes[index], key})).filter(binding => binding.node);
  });
  const attributes = [...document.querySelectorAll('[data-i18n-attrs]')].flatMap(element => Object.entries(JSON.parse(element.dataset.i18nAttrs)).map(([attribute, key]) => ({element, attribute, key})));
  const t = key => language === 'ko' ? (messages[key] ?? key) : key;
  window.siteI18n = {t, get language() { return language; }};
  const toggle = document.getElementById('language-toggle');
  toggle.addEventListener('click', () => {
    language = language === 'ko' ? 'en' : 'ko';
    document.documentElement.lang = language;
    textBindings.forEach(({node,key}) => { node.textContent = t(key); });
    attributes.forEach(({element,attribute,key}) => element.setAttribute(attribute,t(key)));
    toggle.setAttribute('aria-checked', String(language === 'en'));
    toggle.setAttribute('aria-label', t(language === 'ko' ? 'View in English' : 'View in Korean'));
    const url = new URL(location.href);
    if (/^\/index(?:\.(?:ko|en))?\.html$/.test(url.pathname)) url.pathname = '/';
    url.searchParams.set('lang', language);
    history.replaceState(history.state, '', url);
    window.dispatchEvent(new CustomEvent('languagechange', {detail:{language}}));
  });
